import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

/**
 * Builds the demo agreement used by "Load sample data". It is deliberately generic and marked
 * SAMPLE on every page: it is NOT the MIND agreement and is only there to try the product.
 */
export async function buildSampleAgreementPdf(): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const regular = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.1, 0.12, 0.18);
  const grey = rgb(0.45, 0.48, 0.55);

  const paragraphs: [string, string][] = [
    ["1. Purpose", "This sample document exists only to demonstrate SignFlow AI. It has no legal effect and does not represent any real agreement between any real parties."],
    ["2. Services", "The Company will provide the services described in the client file. Work begins once this agreement has been signed by the Client."],
    ["3. Fees", "Fees are set out in the engagement schedule for the file. This sample contains no real fee terms."],
    ["4. Confidentiality", "Each party keeps the other party's confidential information private and uses it only to deliver the services."],
    ["5. Term", "This agreement starts on the date of signature and continues until the file is closed."],
  ];

  const header = (page: ReturnType<typeof doc.addPage>, n: number) => {
    page.drawText("SAMPLE — FOR DEMONSTRATION ONLY", { x: 56, y: 752, size: 9, font: bold, color: rgb(0.75, 0.2, 0.2) });
    page.drawText(`Page ${n} of 2`, { x: 500, y: 752, size: 9, font: regular, color: grey });
  };

  const p1 = doc.addPage([612, 792]);
  header(p1, 1);
  p1.drawText("Sample Client Services Agreement", { x: 56, y: 700, size: 22, font: bold, color: ink });
  p1.drawText("Demo document generated by SignFlow AI. Not a real agreement.", { x: 56, y: 678, size: 10, font: regular, color: grey });
  let y = 630;
  for (const [title, body] of paragraphs) {
    p1.drawText(title, { x: 56, y, size: 12, font: bold, color: ink });
    y -= 18;
    for (const line of wrapText(body, 92)) {
      p1.drawText(line, { x: 56, y, size: 10.5, font: regular, color: ink });
      y -= 15;
    }
    y -= 14;
  }

  const p2 = doc.addPage([612, 792]);
  header(p2, 2);
  p2.drawText("Acceptance", { x: 56, y: 700, size: 16, font: bold, color: ink });
  p2.drawText("By signing below, the Client confirms they have read this sample agreement.", { x: 56, y: 672, size: 10.5, font: regular, color: ink });
  const line = (label: string, x: number, yy: number, w: number) => {
    p2.drawLine({ start: { x, y: yy }, end: { x: x + w, y: yy }, thickness: 0.8, color: ink });
    p2.drawText(label, { x, y: yy - 14, size: 9, font: regular, color: grey });
  };
  line("Client signature", 56, 560, 240);
  line("Date", 340, 560, 140);
  line("Client full name", 56, 480, 240);

  return doc.save();
}

/** Field layout matching the lines drawn above (fractions of a 612 x 792 page). */
